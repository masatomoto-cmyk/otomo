function Feedback() {
  return (
    <>
      <p>
        曲を作っても、聴いてくれる人がいなければ上達のヒントは得られません。SNS に上げても「いいね」の数しか分からない……
        という人に向けて、ちゃんと言葉で感想をもらうためのコツをまとめました。
      </p>

      <h2>感想が返ってきやすい投稿の書き方</h2>
      <ul>
        <li>
          <strong>「どこを聴いてほしいか」を書く</strong> — 「サビのメロディが覚えやすいか」「ミックスで低音が出すぎていないか」など、
          質問がはっきりしているほど答えやすくなります。
        </li>
        <li><strong>作った背景をひとこと</strong> — 「初めてDAWで作った曲です」「ライブ用に短くしたバージョン」など、聴く側の前提がそろいます。</li>
        <li><strong>短く聴けるようにする</strong> — 長い曲なら「1:20からのサビだけでも」と書くと、気軽に聴いてもらえます。</li>
        <li><strong>参考にした曲を書く</strong> — 目指している音が伝わると、的外れな感想が減ります。</li>
      </ul>

      <h2>どこに載せるか</h2>
      <p>
        音源は SoundCloud・YouTube などに置き、そのリンクを感想をもらえる場所に共有するのが手軽です。
        OTOMO の <Link to="/tracks">作品シェア</Link> では、YouTube・SoundCloud・Spotify のリンクがそのまま再生でき、
        「フィードバック募集中」を付けて投稿できます。まだ誰からも感想をもらっていない作品は「感想待ち」として見つけてもらいやすくなっています。
      </p>

      <h2>もらった感想の活かし方</h2>
      <ul>
        <li><strong>すぐに全部直さない</strong> — 同じ指摘が複数の人から来たら、それは直す価値が高いポイントです。</li>
        <li><strong>好みと改善点を分ける</strong> — 「ジャンル的に好きじゃない」と「ボーカルが聴き取りにくい」は別物です。</li>
        <li><strong>お礼と、直した版を返す</strong> — 改善版を見せると、次も聴いてもらいやすくなります。</li>
      </ul>

      <h2>感想を書く側のコツ</h2>
      <p>
        感想は、もらうだけでなく送ることで関係が生まれます。「良かったところ」を一つ具体的に挙げてから、
        「気になったところ」を一つ書くと、相手も受け取りやすくなります。うまく言葉にできないときは、OTOMO の
        「🎧 聴いたよ」「✨ 刺さった」を送るだけでも作り手には届きます。
      </p>
    </>
  )
}

function Session() {
  return (
    <>
      <p>
        バンドを組んでいなくても、人と音を合わせる楽しさは味わえます。その入り口になるのが「セッション」と「オープンマイク」です。
        はじめて参加する前に知っておきたいことをまとめました。
      </p>

      <h2>セッションとオープンマイクの違い</h2>
      <ul>
        <li>
          <strong>セッション（ジャムセッション）</strong> — その場に集まった人で即興的に演奏する集まりです。
          ジャズ・ブルース・ファンク・ロックなど、ジャンルごとに開かれていることが多く、定番曲（スタンダード）を使うこともあります。
        </li>
        <li>
          <strong>オープンマイク</strong> — 1人ずつ（または1組ずつ）順番にステージで演奏できるイベントです。弾き語りや朗読、
          お笑いまで幅広く、1組10〜15分ほど。持ち曲を人前で試したい人に向いています。
        </li>
      </ul>

      <h2>はじめて参加するときの流れ</h2>
      <ol>
        <li><strong>雰囲気が合いそうなイベントを選ぶ</strong> — 「初心者歓迎」と書かれた回や、ジャンルが自分に近いものから。</li>
        <li><strong>受付で名前とパートを伝える</strong> — セッションは、ホストが順番に組み合わせを決めてくれることが多いです。</li>
        <li><strong>最初は見学しながら様子をつかむ</strong> — どの曲がよく演奏されるか、ソロの回し方などが分かります。</li>
        <li><strong>呼ばれたら演奏する</strong> — 分からない曲は正直に伝えて大丈夫です。キーとテンポを確認してから始めます。</li>
      </ol>

      <h2>持ち物</h2>
      <ul>
        <li>楽器（ギター・ベースならシールドとチューナー、ドラムならスティック）</li>
        <li>弾き語りならカポやピック、歌詞やコード譜</li>
        <li>参加費・ドリンク代（1,000〜2,000円前後が多い）</li>
      </ul>

      <h2>初参加のマナー</h2>
      <ul>
        <li>ほかの人のソロ中は音量を下げて、聴く姿勢で。</li>
        <li>長いソロや、ずっとステージに残るのは控えめに。</li>
        <li>終わったら一緒に演奏した人にひとこと声をかけると、次の機会につながります。</li>
      </ul>

      <p>
        近くのセッションやオープンマイクは <Link to="/events">ライブ・イベント</Link> で探せます。自分でセッションを主催するときも、
        無料で告知できます。気が合う人がいたら、<Link to="/recruits">バンドメンバー募集</Link> でバンドに誘ってみるのも一つの手です。
      </p>
    </>
  )
}
